import torch
from torch import nn
from .base_loss import BaseLoss

class VLM_ELBO_Combined(BaseLoss):
    """
    An ELBO-based loss for a VLM attacker.

    This version assumes the image generation (via diffusion) happens *before* this 
    loss function is called. The `forward` method receives the final text inputs and 
    the generated images that are ready to be passed to the target VLM.
    
    The log_likelihoods, entropies, and log_prior still correspond to the attacker's 
    original generation of the (text_input, image_prompt) pair.
    """

    def __init__(self, target_lm, judge, device, 
                 entropy_coef=0.08, kl_coef=0.3):
        """
        Initializes the loss module.

        Args:
            target_lm (nn.Module): The target VLM to be attacked.
            judge (nn.Module): The judge model that scores responses.
            device (torch.device): The device for tensor computations (e.g., 'cuda').
            entropy_coef (float): Base coefficient for the entropy bonus.
            kl_coef (float): Coefficient for the KL divergence penalty.
        """
        # The diffusion_model is no longer needed here.
        super().__init__(target_lm, judge, device)
        
        self.H = entropy_coef
        self.KL = kl_coef

    def forward(self, text_inputs, generated_images, log_likelihoods, entropies, log_prior):
        """
        Calculates the loss for a batch of text inputs and generated images.

        Args:
            text_inputs (list[str]): A batch of text inputs generated by the attacker.
            generated_images (torch.Tensor): A batch of images generated by the diffusion model.
            log_likelihoods (torch.Tensor): Joint log probabilities log q_theta(text, image_prompt).
            entropies (torch.Tensor): Entropies of the attacker's generation policy.
            log_prior (torch.Tensor): Log probabilities from the prior model log P(text, image_prompt).

        Returns:
            dict: A dictionary containing the loss and various metrics for logging.
        """
        
        # 1. Get responses from the target VLM using the provided text and images.
        responses = self.target_lm.batch_respond(text_inputs, generated_images)

        # 2. Get the reward (log judge scores) from the Judge model.
        with torch.no_grad():
            # The judge might need the text, the response, or both. Adjust as needed.
            log_judge_scores = self.judge.batch_judge_train(text_inputs, responses).to(self.device)

        actual_judge_scores = log_judge_scores.exp()
        
        # 3. Calculate the REINFORCE gradient estimator components (pg, ent, kl).
        # This core logic remains unchanged, as it operates on the probabilities of the
        # attacker's actions, which are the text and image prompts.
        
        # Policy Gradient (PG) term
        weights = (log_judge_scores - log_likelihoods)
        pg = -1 * (weights.detach()) * log_likelihoods
        
        # KL Divergence term
        kl = self.KL * (log_likelihoods - log_prior)
        
        # Adaptive Entropy (Ent) term
        with torch.no_grad():
            pg_mag = (weights * (-log_likelihoods)).abs().mean()
            ent_mag = entropies.mean()
            gamma = pg_mag / (ent_mag + 1e-8)
        
        target_H = 1.2
        gamma += 0.02 * (entropies.mean().item() - target_H)
        gamma = max(gamma, 0.0)
        
        ent = -gamma * self.H * entropies

        # 4. Combine components into the final loss.
        loss = (pg + kl + ent).mean()

        # 5. Prepare a dictionary for logging.
        loss_dct = {
            "loss": loss,
            "pg_loss": pg.mean().item(),
            "kl_loss": kl.mean().item(),
            "ent_loss": ent.mean().item(),
            "gamma": gamma,
            "entropy": entropies.mean().item(),
            "judge_score_mean": actual_judge_scores.mean().item(),
            "text_inputs": text_inputs,
            "responses": responses,
            "judge_scores": actual_judge_scores.cpu().tolist(),
        }

        return loss_dct